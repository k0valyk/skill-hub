export const dictionaries: Record<Lang, Dict> = { uk, en };

export type TranslationKey = keyof typeof uk;

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const dict = dictionaries[lang] ?? dictionaries.uk;
  let value = dict[key] ?? dictionaries.uk[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function kindLabel(lang: Lang, kind: string): string {
  return translate(lang, `kind.${kind}` as TranslationKey);
}

export function kindOne(lang: Lang, kind: string): string {
  return translate(lang, `kind.${kind}.one` as TranslationKey);
}
